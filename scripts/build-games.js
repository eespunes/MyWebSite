#!/usr/bin/env node
// Build v1.161 · 2026-11-06
/* Writes the thin per-game shells, games/<slug>/index.html, one per row of
   the Games table in CONTENT.md. <slug> is the end of the row's Link,
   games/<slug>/.
   Everything on the page is built at load time by games/game.js from
   CONTENT.md, so this only needs re-running when a game is added or renamed. */
const fs = require("node:fs");
const path = require("node:path");
const CVParse = require("../assets/js/parse.js");

const ROOT = path.join(__dirname, "..");
const doc = CVParse.parse(fs.readFileSync(path.join(ROOT, "CONTENT.md"), "utf8"));
const games = CVParse.index(doc).games;
const site = (CVParse.index(doc).nav || { fields: {} }).fields.brand || "Erik Espuñes Jubero";

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const slugOf = (link) => String(link || "").replace(/\/+$/, "").split("/").pop();

function shell(row) {
  const slug = slugOf(row.link);
  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(row.game)} · ${esc(site)}</title>
    <meta name="description" content="${esc(row.game)}: ${esc(row.subtitle)}, ${esc(row.year)}. Play or download it here." />
    <meta name="theme-color" content="#121212" />
    <link rel="shortcut icon" href="../../assets/images/favicon.png" />

    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Poppins:wght@300;400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet" />
    <link rel="stylesheet" href="../../projects/case-study.css" />
    <link rel="stylesheet" href="../game.css" />
  </head>

  <body>
    <!-- Generated by scripts/build-games.js. The page is built from
         CONTENT.md (## Games) by ../game.js; edit that, not this file. -->
    <div id="game" data-slug="${esc(slug)}"></div>
    <noscript><p class="noscript">${esc(row.game)}: this page needs JavaScript to show the game.</p></noscript>
    <script src="../../assets/js/parse.js"></script>
    <script src="../game.js"></script>
  </body>
</html>
`;
}

const rows = games.tables[0] || [];
for (const row of rows) {
  const dir = path.join(ROOT, "games", slugOf(row.link));
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), shell(row));
}
console.log(`${rows.length} game pages → games/<slug>/index.html`);
