#!/usr/bin/env node
// Build v1.166 · 2026-11-10
/* Writes the language folders, one per row of ## Translations in CONTENT.md
   (es/, ca/, nl/): copies of index.html and cv.html whose <html> tells
   lang.js which content file to read and how to reach the root.

   Also writes the canonical and hreflang links into every copy and into the
   root pages, between the <!-- languages --> markers, so search engines see
   one page in four languages rather than four competing pages.

   Re-run after changing index.html, cv.html or the Translations table. The
   tests fail while the folders are out of date. */
const fs = require("node:fs");
const path = require("node:path");
const CVParse = require("../assets/js/parse.js");
const CVLang = require("../assets/js/lang.js");

const ROOT = path.join(__dirname, "..");
const PAGES = ["index.html", "cv.html"];

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");
const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const english = CVParse.parse(read("CONTENT.md"));
const languages = CVLang.translations(english);

/* The live address, from the CV-only Website row in ## Contact. */
const site = (() => {
  const rows = CVParse.index(english).contact.tables[0] || [];
  const row = rows.find((r) => /^yes$/i.test(r["cv only"] || "") && /^https?:/.test(r.link || ""));
  return row.link.replace(/\/?$/, "/");
})();

const folder = (lang) => lang.path.replace(/^\/+/, "");
const address = (lang, page) => site + folder(lang) + (page === "index.html" ? "" : page);

function block(page, current) {
  const lines = [`<link rel="canonical" href="${address(current, page)}" />`];
  for (const lang of languages) {
    lines.push(`<link rel="alternate" hreflang="${lang.code}" href="${address(lang, page)}" />`);
  }
  const fallback = languages.find((l) => folder(l) === "") || languages[0];
  lines.push(`<link rel="alternate" hreflang="x-default" href="${address(fallback, page)}" />`);
  return (
    "    <!-- languages: written by scripts/build-languages.js -->\n" +
    lines.map((l) => `    ${l}\n`).join("") +
    "    <!-- /languages -->\n"
  );
}

const MARKERS = /^ {4}<!-- languages:[^\n]*-->\n[\s\S]*?^ {4}<!-- \/languages -->\n/m;

function withBlock(html, page, lang) {
  if (!MARKERS.test(html)) throw new Error(`${page} has no <!-- languages --> markers`);
  return html.replace(MARKERS, block(page, lang));
}

function translated(html, page, lang) {
  const depth = folder(lang).split("/").filter(Boolean).length;
  const back = "../".repeat(depth);
  const doc = CVLang.merge(english, CVParse.parse(read(lang.file)));
  const by = CVParse.index(doc);
  const brand = (by.nav && by.nav.fields.brand) || "";

  let out = html
    /* Only the root pages carry the build stamp (scripts/version.js). */
    .replace(/^\s*<meta name="version"[^\n]*\n/m, "")
    .replace(
      /<html lang="[^"]*">/,
      `<html lang="${esc(lang.code)}" data-root="${back}" data-content="${esc(lang.file)}">`
    )
    .replace(
      /^(\s*<meta charset[^\n]*\n)/m,
      `$1    <!-- Generated by scripts/build-languages.js from /${page}; edit that, not this. -->\n`
    )
    /* Assets live once, at the root; index.html and cv.html are this folder's own. */
    .replace(
      /\b(href|src)="(?![a-z][a-z0-9+.-]*:|\/|#|index\.html|cv\.html)([^"]+)"/gi,
      `$1="${back}$2"`
    );

  if (page === "index.html" && by.meta) {
    out = out
      .replace(/<title>[^<]*<\/title>/, `<title>${esc(by.meta.fields.title)}</title>`)
      .replace(
        /<meta name="description" content="[^"]*" \/>/,
        `<meta name="description" content="${esc(by.meta.fields.description)}" />`
      );
  } else if (page === "cv.html" && brand) {
    out = out.replace(/<title>[^<]*<\/title>/, `<title>${esc(brand)} — CV</title>`);
  }
  return withBlock(out, page, lang);
}

/* Every file this script owns → its contents. */
function render() {
  const files = {};
  for (const page of PAGES) {
    const source = read(page);
    for (const lang of languages) {
      const dir = folder(lang);
      files[path.posix.join(dir, page)] = dir ? translated(source, page, lang) : withBlock(source, page, lang);
    }
  }
  return files;
}

module.exports = { render, languages };

if (require.main === module) {
  const files = render();
  for (const [rel, html] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, rel), html);
  }
  console.log(`${languages.length} languages → ${Object.keys(files).join(", ")}`);
}
